#!/usr/bin/env node
// Extracts Playwright's browser-side InjectedScript engine source out of the
// installed playwright-core's opaque lib/coreBundle.js (its internals stopped
// being separately requirable at playwright-core@1.60.0) and writes it as a
// plain exported constant that packages/mobilewright-core can import.
//
// The engine source lives in the bundle as a single large string-literal
// assignment, anchored by an esbuild-emitted module-boundary comment that
// marks the original module's path. That comment is a stable byproduct of
// Playwright's own build (kept for its source maps/debugging), so it's a far
// more durable anchor than any internal file path or symbol name.
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFileSync, mkdirSync } from 'node:fs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const corePkgDir = join(__dirname, '..', 'packages', 'mobilewright-core');
const require = createRequire(join(corePkgDir, 'package.json'));

const ANCHOR = '// packages/playwright-core/src/generated/injectedScriptSource.ts';
const ASSIGNMENT_MARKER = /\bsource\d*\s*=\s*'/;
const OUTPUT_PATH = join(corePkgDir, 'src', 'generated', 'injected-script-source.ts');

function fail(reason) {
  console.error(
    `[sync-playwright-injected-script] Failed to extract Playwright's InjectedScript ` +
    `source: ${reason}\n` +
    `playwright-core's internal bundle layout likely changed in this version. ` +
    `Inspect node_modules/playwright-core/lib/coreBundle.js and update the anchor/pattern ` +
    `in this script accordingly.`,
  );
  process.exit(1);
}

let bundlePath;
try {
  const pkgRoot = dirname(require.resolve('playwright-core/package.json'));
  bundlePath = join(pkgRoot, 'lib', 'coreBundle.js');
} catch (e) {
  fail(`could not resolve playwright-core (${e.message})`);
}

const fs = await import('node:fs/promises');
let bundleText;
try {
  bundleText = await fs.readFile(bundlePath, 'utf8');
} catch (e) {
  fail(`could not read ${bundlePath} (${e.message})`);
}

const anchorIndex = bundleText.indexOf(ANCHOR);
if (anchorIndex === -1) fail(`anchor comment not found: ${ANCHOR}`);

const afterAnchor = bundleText.slice(anchorIndex);
const assignMatch = afterAnchor.match(ASSIGNMENT_MARKER);
if (!assignMatch) fail(`string-literal assignment not found after anchor`);

const literalStart = anchorIndex + assignMatch.index + assignMatch[0].length;
let i = literalStart;
let inEscape = false;
while (i < bundleText.length) {
  const ch = bundleText[i];
  if (inEscape) {
    inEscape = false;
    i++;
    continue;
  }
  if (ch === '\\') {
    inEscape = true;
    i++;
    continue;
  }
  if (ch === "'") break;
  i++;
}
if (i >= bundleText.length) fail('unterminated string literal (no matching closing quote found)');

const literalBody = bundleText.slice(literalStart, i);
let injectedSource;
try {
  // Bounded to decoding a single string-literal expression, not arbitrary code.
  injectedSource = new Function(`return ('${literalBody}')`)();
} catch (e) {
  fail(`extracted literal did not decode as a string (${e.message})`);
}

if (typeof injectedSource !== 'string' || injectedSource.length < 100_000) {
  fail(`decoded source looks too small (${injectedSource?.length ?? 0} chars) to be the real engine`);
}
if (!injectedSource.includes('InjectedScript')) {
  fail(`decoded source does not contain "InjectedScript"`);
}

const header =
  '// AUTO-GENERATED by scripts/sync-playwright-injected-script.mjs — do not edit by hand.\n' +
  '// Extracted from the installed playwright-core\'s lib/coreBundle.js. Committed to git;\n' +
  '// run `npm run sync:playwright` after bumping the playwright version and commit the\n' +
  '// result. CI fails the build if this file drifts from what the script produces.\n';
const contents = `${header}export const INJECTED_SOURCE: string = ${JSON.stringify(injectedSource)};\n`;

mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
writeFileSync(OUTPUT_PATH, contents);
console.log(`[sync-playwright-injected-script] Wrote ${injectedSource.length} chars to ${OUTPUT_PATH}`);
